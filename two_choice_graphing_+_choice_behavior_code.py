def compute_mean_sem(df: pd.DataFrame, exclude_zeros: bool):
    if exclude_zeros:
        df = df.mask(df == 0, np.nan)
    mean_vals = df.mean(axis=1, skipna=True).values
    sem_vals = df.std(axis=1, skipna=True).values / np.sqrt(df.count(axis=1))
    return mean_vals, sem_vals


def add_shaded_region(ax, start_time, end_time, color, label):
    ymin, ymax = ax.get_ylim()
