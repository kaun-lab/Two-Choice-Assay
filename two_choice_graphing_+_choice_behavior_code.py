def clean_and_sum_csvs(filepaths):
    cleaned_dfs = []
    for path in filepaths:
        try:
            df_raw = pd.read_csv(path, header=None, dtype=str, encoding='utf-8-sig')
        except UnicodeDecodeError:
            df_raw = pd.read_csv(path, header=None, dtype=str, encoding='latin1')

        def clean_cell(x):
            x_stripped = str(x).strip()
            if '*' in x_stripped:
                return np.nan
            try:
                return float(x_stripped)
            except ValueError:
                return np.nan

        cleaned_df = df_raw.applymap(clean_cell)
        cleaned_dfs.append(cleaned_df)

    summed_df = sum(cleaned_dfs)
    summed_df = summed_df.dropna(how='all', axis=0).dropna(how='all', axis=1)
    return summed_df


def average_two_csvs(csv1: str, csv2: str, output_path: str):
    df1 = pd.read_csv(csv1)
    df2 = pd.read_csv(csv2)
    df_avg = pd.DataFrame()
    df_avg['Mean'] = (df1['Mean'] + df2['Mean']) / 2
    df_avg['SEM'] = (df1['SEM'] + df2['SEM']) / 2
    df_avg.to_csv(output_path, index=False)
    return df_avg


