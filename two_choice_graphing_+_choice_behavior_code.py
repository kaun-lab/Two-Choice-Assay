def process_file(file_path, folder_label):
    df = pd.read_csv(file_path)
    results = {}
    total_frames = df.shape[0]

    for animal in df.columns:
        series = df[animal].astype(str)
        total_time_A = (series.str.strip().str.upper() == 'A').sum() / FPS
        total_time_B = (series.str.strip().str.upper() == 'B').sum() / FPS

        if total_time_A >= (total_frames / FPS) - 0.5 or total_time_B >= (total_frames / FPS) - 0.5 or total_time_A < 0.5 or total_time_B < 0.5:
            excluded_animals.append(f"{animal}_{folder_label}_{os.path.basename(file_path).replace('.csv','')}")
            continue

        for window_name, (start_s, end_s) in TIME_WINDOWS.items():
            start_frame = start_s * FPS
            end_frame = end_s * FPS
            if end_frame > total_frames:
                end_frame = total_frames

            df_window = series.iloc[start_frame:end_frame]
            bouts = {'A': [], 'B': []}

            current_side = str(df_window.iloc[0]).strip()
            bout_length = 1

            for side in df_window.iloc[1:]:
                side = str(side).strip()
                if side == current_side:
                    bout_length += 1
                elif side in bouts:
                    bouts[current_side].append(bout_length / FPS)
                    current_side = side
                    bout_length = 1
                else:
                    current_side = side
                    bout_length = 1

            if current_side in bouts:
                bouts[current_side].append(bout_length / FPS)

            unique_animal_id = f"{animal}_{folder_label}_{os.path.basename(file_path).replace('.csv','')}"

            if unique_animal_id not in results:
                results[unique_animal_id] = {}

            for side_key in ['A', 'B']:
                mean_bout = sum(bouts[side_key]) / len(bouts[side_key]) if bouts[side_key] else 0
                results[unique_animal_id][f'{side_key}_{window_name}'] = mean_bout

                if 'EA' in file_path:
                    if side_key == 'A':
                        aggregated_EA_A.setdefault(window_name, {})[unique_animal_id] = mean_bout
                    if side_key == 'B':
                        aggregated_EA_B.setdefault(window_name, {})[unique_animal_id] = mean_bout
                if 'IAAc' in file_path:
                    if side_key == 'A':
                        aggregated_IAAc_A.setdefault(window_name, {})[unique_animal_id] = mean_bout
                    if side_key == 'B':
                        aggregated_IAAc_B.setdefault(window_name, {})[unique_animal_id] = mean_bout

    return pd.DataFrame.from_dict(results, orient='index')

