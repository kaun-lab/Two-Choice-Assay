def process_metrics_data(
    root_folder, save_path, plot_binned=False, export_binned_csvs=True,
    quartile_basis="Rolling_Preference_A", transition_check_range=(0, 4050),
    bin_size=450, fig_size=(5, 5), pdf_dpi=300,
    label_choice="Choice", label_post="Post-Choice",
    line_choice=15, line_post=45,
    label_fontsize=8, label_rotation=90
):
    num_frames = 4050
    frames = list(range(1, num_frames + 1))

    ratio_A_subjects = {}
    ratio_B_subjects = {}

    for timestamp_folder in os.listdir(root_folder):
        for subfolder in ["Top", "Bottom"]:
            subfolder_path = os.path.join(root_folder, timestamp_folder, subfolder)
            if not os.path.isdir(subfolder_path):
                continue

            merged_path = None
            for file in os.listdir(subfolder_path):
                if "Merged_Region" in file:
                    merged_path = os.path.join(subfolder_path, file)
                    break

            if not merged_path or not os.path.exists(merged_path):
                print(f"[SKIP] Merged_Region file not found in: {subfolder_path}")
                continue

            try:
                df = pd.read_csv(merged_path)
                if df.shape[1] <= 1:
                    print(f"[SKIP] File too narrow: {merged_path} → shape={df.shape}")
                    continue

                df = df.iloc[:num_frames, 1:]
                if df.empty:
                    print(f"[SKIP] Empty data after trimming: {merged_path}")
                    continue

                for col in df.columns:
                    col_data = df[col]
                    counts_A = col_data.eq('A').astype(int)
                    counts_B = col_data.eq('B').astype(int)

                    with np.errstate(divide='ignore', invalid='ignore'):
                        ratio_A = (counts_A - counts_B) / (counts_A + counts_B)
                        dropped = ratio_A.isna().sum()
                        ratio_A = ratio_A.dropna()
                        ratio_B = -ratio_A

                    subject_label = f"{timestamp_folder}_{subfolder}_{col}"
                    ratio_A_subjects[subject_label] = ratio_A.values
                    ratio_B_subjects[subject_label] = ratio_B.values

                    print(f"[OK] Loaded {subject_label} → {len(ratio_A)} frames (Dropped {dropped} NaNs)")

            except Exception as e:
                print(f"[ERROR] {merged_path}: {e}")

    def plot_preference_index(subject_data, label):
        df = pd.DataFrame({'Frame': frames[:num_frames], 'Time_s': [f / 30 for f in frames[:num_frames]]})
        for subject, data in subject_data.items():
            if len(data) < num_frames:
                data = np.pad(data, (0, num_frames - len(data)), constant_values=np.nan)
            df[subject] = data

        save_df = df.drop(columns=['Time_s'])
        save_df.to_csv(os.path.join(save_path, f"Raw_Ratio_{label}_Preference_Index_Over_Time.csv"), index=False)

        plt.figure(figsize=fig_size)
        avg = df.iloc[:, 2:].mean(axis=1)
        err = sem(df.iloc[:, 2:], axis=1, nan_policy='omit')
        smoothed_avg = gaussian_filter1d(avg, sigma=10)
        smoothed_err = gaussian_filter1d(err, sigma=10)

        plt.plot(df['Time_s'], smoothed_avg, color='blue' if label == 'A' else 'red')
        plt.fill_between(df['Time_s'], smoothed_avg - smoothed_err, smoothed_avg + smoothed_err,
                         color='lightblue' if label == 'A' else 'lightcoral', alpha=0.5)
        plt.ylim(-1, 1)
        plt.xlabel("Time (s)")
        plt.ylabel("Preference Index")
        plt.title(f"Smoothed Ratio {label} Preference Index Over Time")
        plt.xlim(df['Time_s'].iloc[0], df['Time_s'].iloc[len(smoothed_avg) - 1])

        ax = plt.gca()
        ax.spines['top'].set_visible(False)
        ax.spines['bottom'].set_visible(False)

        max_time = df['Time_s'].iloc[-1]
        ax.set_xticks(np.arange(0, max_time + 1, 15))

        ax.axvline(x=line_choice, color='gray', linestyle='--', linewidth=1)
        ax.axvline(x=line_post, color='gray', linestyle='--', linewidth=1)

        ax.axvspan(line_choice, line_post, color='gray', alpha=0.1)
        ax.text(line_choice, 0.95, label_choice, ha='left', va='top',
                fontsize=label_fontsize, rotation=label_rotation)

        ax.axvspan(line_post, df['Time_s'].iloc[-1], color='gray', alpha=0.05)
        ax.text(line_post, 0.95, label_post, ha='left', va='top',
                fontsize=label_fontsize, rotation=label_rotation)

        ax.legend().remove()
        plt.savefig(os.path.join(save_path, f"Ratio_{label}_Preference_Index_Over_Time.pdf"),
                    transparent=True, dpi=pdf_dpi)
        plt.close()

    plot_preference_index(ratio_A_subjects, "A")
    plot_preference_index(ratio_B_subjects, "B")

    def save_binned_csv(subject_data, label, bin_size=450):
        binned_df = pd.DataFrame()

        for subject, data in subject_data.items():
            if len(data) < num_frames:
                data = np.pad(data, (0, num_frames - len(data)), constant_values=np.nan)
            bins = []
            for start in range(0, num_frames, bin_size):
                end = min(start + bin_size, num_frames)
                bin_mean = np.nanmean(data[start:end])
                bins.append(bin_mean)
            binned_df[subject] = bins

        binned_df.index.name = 'Bin'
        binned_df.to_csv(os.path.join(save_path, f"Binned_Raw_Ratio_{label}_Preference_Index_Over_Time.csv"))

    save_binned_csv(ratio_A_subjects, "A", bin_size=bin_size)
    save_binned_csv(ratio_B_subjects, "B", bin_size=bin_size)

