                plt.figure(figsize=(10, 6))
                avg = df.iloc[:, 1:].mean(axis=1, skipna=True)
                err = sem(df.iloc[:, 1:], axis=1, nan_policy='omit')
                smoothed_avg = gaussian_filter1d(avg, sigma=10)
                smoothed_err = gaussian_filter1d(err, sigma=10)
