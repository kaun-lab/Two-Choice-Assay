                            if df.shape[1] <= max(column_index, region_column_index):
                                continue

                            metric_column = df.iloc[:num_frames, column_index].copy()
                            region_column = df.iloc[:num_frames, region_column_index].copy()

                            metric_column.replace([np.inf, -np.inf], np.nan, inplace=True)
                            metric_column.interpolate(inplace=True)
                            metric_column.fillna(method='bfill', inplace=True)
                            metric_column.fillna(method='ffill', inplace=True)

