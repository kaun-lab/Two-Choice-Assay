                plt.plot(frames, smoothed_avg, color=line_colors[color_key], label=f'Average {metric_label}')
                plt.fill_between(frames, smoothed_avg - smoothed_err, smoothed_avg + smoothed_err, color=sem_colors[color_key], alpha=0.5)
                plt.xlabel("Frames")
                plt.ylabel(f"{metric_label} Value")
                plt.title(f"Smoothed Average {metric_label} Over Time{suffix.replace('_', ' ')}")
