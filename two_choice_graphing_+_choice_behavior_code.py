def analyze_transitions(root_folder, save_path, region_column_index, num_frames):
    transition_types = {
        "A to B transitions": ("A", "B"),
        "B to A transitions": ("B", "A"),
        "total transitions": None
    }
    transition_bins = [(150, "5sec"), (300, "10sec"), (450, "15sec")]

    transitions_by_type = {k: {} for k in transition_types}
    lengths_by_subject = {}
    exclusions = []

    for timestamp_folder in os.listdir(root_folder):
        timestamp_path = os.path.join(root_folder, timestamp_folder)
        if not os.path.isdir(timestamp_path):
            continue

        for subfolder in ["Top", "Bottom"]:
            folder_path = os.path.join(timestamp_path, subfolder, "Individual CSVs")
            if not os.path.exists(folder_path):
                continue

            for file in os.listdir(folder_path):
                if file.endswith("Annotated.csv"):
                    file_path = os.path.join(folder_path, file)
                    subject_name = f"{timestamp_folder}_{subfolder}_{file.replace(' Annotated.csv', '')}"
                    try:
                        df = pd.read_csv(file_path)
                        if df.shape[1] <= region_column_index:
                            continue
                        region_series = df.iloc[:num_frames, region_column_index].astype(str)
                        actual_length = len(region_series)
                        if actual_length < 4050:
                            exclusions.append({"File": file_path, "Length": actual_length})
                            print(f"Excluded {file_path} due to insufficient length ({actual_length} frames).")
                            continue
                        transitions = region_series.shift(1) + ">" + region_series
                        a2b = transitions[transitions == "A>B"].index.tolist()
                        b2a = transitions[transitions == "B>A"].index.tolist()
                        any_switch = sorted(a2b + b2a)

                        transitions_by_type["A to B transitions"][subject_name] = a2b
                        transitions_by_type["B to A transitions"][subject_name] = b2a
                        transitions_by_type["total transitions"][subject_name] = any_switch
                        lengths_by_subject[subject_name] = actual_length

                    except Exception as e:
                        print(f"Transition error in {file_path}: {e}")

    for label, data in transitions_by_type.items():
        if label == "total transitions":
            continue

        for bin_size, bin_label in transition_bins:
            bin_results = {}
            max_bins = 0
            for subject, indices in data.items():
                actual_length = lengths_by_subject[subject]
                bins = [0] * (actual_length // bin_size + 1)
                for idx in indices:
                    bin_idx = idx // bin_size
                    bins[bin_idx] += 1
                bin_results[subject] = bins
                max_bins = max(max_bins, len(bins))

            for subject in bin_results:
                bins = bin_results[subject]
                if len(bins) < max_bins:
                    bins.extend([0] * (max_bins - len(bins)))
                bin_results[subject] = bins

            df_out = pd.DataFrame.from_dict(bin_results, orient='columns')
            df_out = df_out.fillna(0).astype(int)
            csv_filename = f"{label.replace(' ', '_')}_{bin_label}.csv"
            output_path = os.path.join(save_path, csv_filename)
            df_out.to_csv(output_path, index=False)
            print(f"Saved: {output_path}")

    # Save total transitions count CSV
    total_transitions_data = transitions_by_type["total transitions"]
    total_counts = {subject: len(indices) for subject, indices in total_transitions_data.items()}
    df_out = pd.DataFrame(list(total_counts.items()), columns=["Subject", "Total_Transitions"])
    output_path = os.path.join(save_path, "total_transitions_count.csv")
    df_out.to_csv(output_path, index=False)
    print(f"Saved: {output_path}")

    if exclusions:
        exclusions_df = pd.DataFrame(exclusions)
        exclusions_path = os.path.join(save_path, "exclusions_log.csv")
        exclusions_df.to_csv(exclusions_path, index=False)
        print(f"Saved exclusions log: {exclusions_path}")


