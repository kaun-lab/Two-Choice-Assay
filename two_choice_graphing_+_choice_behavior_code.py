def process_combined(csv_folder):
    combined_df = None
    subject_counter = 0

    for file in os.listdir(csv_folder):
        if "Raw" in file and "Preference_Index_Over_Time" in file and file.endswith(".csv"):
            file_path = os.path.join(csv_folder, file)
            df = pd.read_csv(file_path)
            df_filtered = df.iloc[0:4050, :]

            valid_columns = []
            for column in df_filtered.columns[1:]:
                values = df_filtered[column].values
                sign_changes = np.diff(np.sign(values))
                if np.any(sign_changes != 0):
                    valid_columns.append(column)
                else:
                    print(f"[EXCLUDE] Column {column} in {file} has no transitions.")

            if combined_df is None:
                combined_df = df[valid_columns]
            else:
                combined_df = pd.concat([combined_df, df[valid_columns]], axis=1)

            subject_counter += len(valid_columns)
            print(f"[OK] Loaded {file} with {len(valid_columns)} valid subjects")

    if combined_df is None or subject_counter == 0:
        print("ERROR: No data found in Raw CSVs.")
        return None, None, None

    frames = np.arange(len(combined_df))
    seconds = frames / 30.0
    avg = combined_df.mean(axis=1)
    err = sem(combined_df, axis=1, nan_policy='omit')
    smoothed_avg = gaussian_filter1d(avg, sigma=10)
    smoothed_err = gaussian_filter1d(err, sigma=10)

    return seconds, smoothed_avg, smoothed_err

